-- 迁移脚本：用户表新增 status 字段（注销/禁用登录）
-- 用途：管理员可注销用户（status=1 后禁止登录），也可恢复（status=0）
-- 说明：若数据库尚未初始化，直接重新执行 init.sql 即可（已包含此字段）；
--       若已初始化，请执行本脚本。
-- =====================================================================
USE lost_found;

ALTER TABLE t_user
    ADD COLUMN status TINYINT NOT NULL DEFAULT 0 COMMENT '0正常 1已注销（禁用登录）' AFTER email;
